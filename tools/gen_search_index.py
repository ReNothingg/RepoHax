"""Builds src/overlay/menu/search_index.h for the menu's feature search.

Each tab source file is scanned for LocKey_* labels. Shared panels that are
defined in one file but shown on another tab are mapped to that tab.
Re-run after adding or moving features:

    python tools/gen_search_index.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
TABS = ROOT / "src" / "overlay" / "menu" / "tabs"
OUT = ROOT / "src" / "overlay" / "menu" / "search_index.h"

# Index in g_Tabs (menu.cpp).
FILE_TAB = {
    "stats_tab.cpp": 0,
    "entities_tab.cpp": 1,
    "vision_tab.cpp": 2,
    "valuables_tab.cpp": 3,
    "items_tab.cpp": 4,
    "level_tab.cpp": 5,
    "cosmetic_tabs.cpp": 6,
    "misc_tab.cpp": 7,
    "settings_tab.cpp": 8,
    "god_tools_tab.cpp": 9,
}

# Shared panels: the tab that actually shows them.
SHARED_PANEL_TAB = {
    "DrawTeamControlPanel": 1,
    "DrawEnemyDirectorControls": 1,
    "DrawEnemyDirectorPanel": 1,
    "DrawWorldControlPanel": 5,
    "DrawLootControlPanel": 3,
    "DrawBalancePanel": 3,
}

# Keys that are values, hints or messages rather than feature names.
SKIP_SUFFIX = ("Desc", "Fmt", "Hint", "Short")
SKIP_PREFIX = ("LocKey_Action",)
SKIP_KEYS = {
    "LocKey_Hotkey", "LocKey_Default", "LocKey_Meters", "LocKey_Yes", "LocKey_No",
    "LocKey_Idle", "LocKey_Unknown", "LocKey_HostOnly", "LocKey_AvailableIfHost",
    "LocKey_Client", "LocKey_HostSingleplayer", "LocKey_InGame", "LocKey_None",
    "LocKey_Small", "LocKey_Medium", "LocKey_Large", "LocKey_FlightControls",
    "LocKey_ToggleFlight", "LocKey_ToggleEyeLasers", "LocKey_EyeLaserHostConnected",
    "LocKey_EyeLaserHostRequired", "LocKey_Degrees", "LocKey_Alive", "LocKey_Dead",
    "LocKey_NotAllHighlighted", "LocKey_TargetReady", "LocKey_NoTarget",
    "LocKey_NetworkObject", "LocKey_LocalObject", "LocKey_GizmoControls",
    "LocKey_ApplyAidKit", "LocKey_WithinSelectedDistance",
}

KEY_RE = re.compile(r"\bLocKey_\w+")
FUNC_RE = re.compile(r"^    void (\w+)\(\)\s*$")


def wanted(key: str) -> bool:
    if key in SKIP_KEYS or key.startswith(SKIP_PREFIX) or key.endswith(SKIP_SUFFIX):
        return False
    return key != "LocKey_Count"


def scan(path: pathlib.Path, default_tab: int, out: dict[int, list[str]]) -> None:
    owner = default_tab
    for line in path.read_text(encoding="utf-8").splitlines():
        m = FUNC_RE.match(line)
        if m:
            owner = SHARED_PANEL_TAB.get(m.group(1), default_tab)
            continue
        if line == "    }":  # end of a namespace-level function
            owner = default_tab
            continue
        for key in KEY_RE.findall(line):
            if wanted(key) and key not in out.setdefault(owner, []):
                out[owner].append(key)


def main() -> None:
    index: dict[int, list[str]] = {}
    for name, tab in FILE_TAB.items():
        scan(TABS / name, tab, index)

    lines = [
        "#pragma once",
        "",
        "// Generated by tools/gen_search_index.py. Do not edit by hand.",
        "",
        '#include "localization.h"',
        "",
        "namespace Cheat",
        "{",
        "    struct SearchEntry",
        "    {",
        "        LocKey Key;",
        "        unsigned char Tab;",
        "    };",
        "",
        "    inline constexpr SearchEntry g_SearchIndex[] =",
        "    {",
    ]
    for tab in sorted(index):
        for key in index[tab]:
            lines.append(f"        {{{key}, {tab}}},")
    lines += ["    };", "}", ""]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {sum(len(v) for v in index.values())} entries")


if __name__ == "__main__":
    main()
